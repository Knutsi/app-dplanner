// Writes prototype/ui/glyphs.js from DPlanner's vendored Tabler glyphs (same keys as the Qt
// app) and prototype/ui/omarchy-themes.js from Omarchy's stock themes. Rerun to refresh.
//   node tools/import-assets.mjs [omarchy themes dir, default /usr/share/omarchy/themes]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../../../..");
const UI = path.join(HERE, "..", "prototype", "ui");

const glyphDir = path.join(REPO, "src/dplanner/theme/glyphs");
const glyphs = {};
for (const file of fs.readdirSync(glyphDir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(glyphDir, file), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  glyphs[file.slice(0, -4)] = inner.replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, "").replace(/\s+/g, " ").trim();
}
fs.writeFileSync(
  path.join(UI, "glyphs.js"),
  `// Generated by tools/import-assets.mjs from src/dplanner/theme/glyphs — Tabler Icons (MIT,\n// Copyright (c) 2020-2026 Paweł Kuna), under DPlanner's own glyph keys. Do not edit.\nexport const GLYPHS = ${JSON.stringify(glyphs, null, 0).replace(/","/g, '",\n  "')};\n`,
);

const themesDir = process.argv[2] ?? "/usr/share/omarchy/themes";
const themes = {};
for (const name of fs.readdirSync(themesDir).sort()) {
  const file = path.join(themesDir, name, "colors.toml");
  if (!fs.existsSync(file)) continue;
  const colors = {};
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const m = line.match(/^\s*([a-z_]+)\s*=\s*"([^"]*)"/);
    if (m) colors[m[1]] = m[2];
  }
  themes[name] = colors;
}
fs.writeFileSync(
  path.join(UI, "omarchy-themes.js"),
  `// Generated by tools/import-assets.mjs from Omarchy's stock themes (${themesDir}). Do not edit.\nexport const OMARCHY_THEMES = ${JSON.stringify(themes)};\n`,
);
console.log(`${Object.keys(glyphs).length} glyphs, ${Object.keys(themes).length} themes`);
